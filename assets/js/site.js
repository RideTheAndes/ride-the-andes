/* ---------- HERO · secuencia de fotos ----------
   La primera imagen viaja en el HTML. Las demás se inyectan DESPUÉS de window.load,
   así el LCP del hero nunca compite con ellas. */
(function(){
  var stack = document.getElementById('heroStack');
  if(!stack) return;
  var list = (stack.dataset.imgs||'').split(',').filter(Boolean);
  if(!list.length) return;
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if(reduce) return;                       // se queda en la primera foto, quieta

  function start(){
    // La rotación solo corre en desktop. En móvil queda la primera foto fija.
    //
    // Medido a 412px: sin este guard el móvil descarga 3 fotos en vez de 1. Con srcset
    // eso sale bien a DPR<=2 (207 KB frente a 297 KB), pero a partir de DPR 2.19 el
    // navegador salta al candidato de 1800w y descarga 764 KB — 467 KB PEOR que la
    // versión anterior de una sola foto, justo en los Android de gama media
    // (412px @ DPR 2.625) que más sufren la tarifa de datos. La rotación es decorativa;
    // no vale ese precio. En desktop se mantiene intacta.
    if(!window.matchMedia('(min-width:1080px)').matches) return;

    list.forEach(function(f){
      // Ruta absoluta: este script también corre en /es/, donde 'assets/…' relativo
      // resolvería a /es/assets/… y daría 404.
      var base = '/assets/img/' + f.trim();
      var img = document.createElement('img');
      img.src = base + '.jpg';
      img.srcset = base + '-750.jpg 750w, ' + base + '-900.jpg 900w, ' +
                   base + '-1200.jpg 1200w, ' + base + '.jpg 1800w';
      img.sizes = '(max-width:1080px) 100vw, 1200px';
      // Duplicados decorativos del primer fotograma: alt="" Y aria-hidden.
      // Los inactivos se ocultan sólo con opacity:0, así que los tres siguen en el árbol
      // de accesibilidad a la vez; sin aria-hidden, un lector de pantalla anunciaría tres
      // descripciones para lo que visualmente es un solo hueco. Sacándolos del árbol, el
      // fotograma del HTML puede llevar un alt real (es el LCP, indexable por Google
      // Images) y se anuncia una sola vez.
      // alt="" solo no basta aquí: deja el <img> en el árbol como imagen sin nombre.
      img.alt = ''; img.setAttribute('aria-hidden', 'true');
      img.width = 1800; img.height = 771;
      img.loading = 'lazy'; img.decoding = 'async';
      stack.appendChild(img);
    });
    var imgs = stack.querySelectorAll('img'), i = 0, timer = null;
    function step(){
      imgs[i].classList.remove('on');
      i = (i + 1) % imgs.length;
      imgs[i].classList.add('on');
    }
    function play(){ if(!timer) timer = setInterval(step, 5200); }
    function pause(){ clearInterval(timer); timer = null; }
    play();
    document.addEventListener('visibilitychange', function(){ document.hidden ? pause() : play(); });
  }
  if(document.readyState === 'complete') start();
  else window.addEventListener('load', start);
})();

/* ---------- BARRA DE AVISOS · rotación y descarte ----------
   El marcado y la caducidad por fecha viven inline en index.html (corren durante
   el parseo para no provocar salto de layout). Aquí solo va lo que puede esperar:
   rotar entre avisos y recordar que el visitante la cerró.

   WCAG 2.2.2 (Pause, Stop, Hide): el botón × es el mecanismo de "hide"; además
   la rotación se pausa al pasar el ratón o al enfocar con teclado, y con
   prefers-reduced-motion no rota en absoluto (se queda el primer aviso). */
(function () {
  var bar = document.getElementById('annbar');
  if (!bar || !document.body.classList.contains('has-ann')) return;

  var close = document.getElementById('annClose');
  if (close) close.addEventListener('click', function () {
    document.body.classList.remove('has-ann');
    try { localStorage.setItem(bar.dataset.key || 'rta-ann', '1'); } catch (e) {}
  });

  var items = [].filter.call(bar.querySelectorAll('.ann-item'), function (li) { return !li.hidden; });
  if (items.length < 2) return;
  if (window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches) return;

  var i = 0, timer = null;
  function step() {
    var cur = items[i];
    cur.classList.add('fade');
    setTimeout(function () {
      cur.classList.remove('on', 'fade');
      i = (i + 1) % items.length;
      var next = items[i];
      next.classList.add('on', 'fade');
      requestAnimationFrame(function () { requestAnimationFrame(function () { next.classList.remove('fade'); }); });
    }, 400);
  }
  function play() { if (!timer) timer = setInterval(step, 7000); }
  function pause() { clearInterval(timer); timer = null; }
  bar.addEventListener('mouseenter', pause);
  bar.addEventListener('mouseleave', play);
  bar.addEventListener('focusin', pause);
  bar.addEventListener('focusout', play);
  document.addEventListener('visibilitychange', function () { document.hidden ? pause() : play(); });
  play();
})();
