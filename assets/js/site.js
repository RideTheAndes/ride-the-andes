// «Añadir al calendario» arma un .ics de día completo en el navegador: nada sale del sitio.
(function () {
  var es = (document.documentElement.lang || 'en').slice(0, 2) === 'es';
  document.addEventListener('click', function (e) {
    var b = e.target.closest && e.target.closest('.dep-cal');
    if (!b) return;
    var d = function (iso, plus) { var t = new Date(iso + 'T12:00:00Z'); t.setUTCDate(t.getUTCDate() + (plus || 0)); return t.toISOString().slice(0, 10).replace(/-/g, ''); };
    var key = b.getAttribute('data-key'), url = 'https://ridetheandes.co/reservar.html?salida=' + key;
    var title = es ? 'La Travesía de Boyacá — Ride The Andes' : 'The Boyacá Traverse — Ride The Andes';
    var desc = es ? 'Diez días, seis etapas en bicicleta por Boyacá. Reserva: ' + url : 'Ten days, six riding stages across Boyacá. Book: ' + url;
    var ics = ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//Ride The Andes//Boyaca Traverse//EN', 'CALSCALE:GREGORIAN', 'BEGIN:VEVENT',
      'UID:traverse-' + key + '@ridetheandes.co', 'DTSTAMP:' + new Date().toISOString().replace(/[-:]/g, '').slice(0, 15) + 'Z',
      'DTSTART;VALUE=DATE:' + d(b.getAttribute('data-start')), 'DTEND;VALUE=DATE:' + d(b.getAttribute('data-end'), 1),
      'SUMMARY:' + title, 'LOCATION:Boyacá\\, Colombia', 'URL:' + url, 'DESCRIPTION:' + desc, 'END:VEVENT', 'END:VCALENDAR'].join('\r\n');
    var a = document.createElement('a');
    a.href = URL.createObjectURL(new Blob([ics], { type: 'text/calendar;charset=utf-8' }));
    a.download = 'ride-the-andes-' + key + '.ics';
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(function () { URL.revokeObjectURL(a.href); }, 4000);
    if (window.plausible) window.plausible('Calendar Added', { props: { salida: key } });
  });
})();
